<?php

namespace App\Console\Commands;

use App\Support\Asset;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

/**
 * 1. Joins public/css/components/*.css into public/css/components.css (one <link> instead
 *    of one per component; no @import chains, no Node). The file is committed; it is only
 *    rewritten when its content really changes.
 * 2. Writes bootstrap/cache/assets.php: content hash of every file under public/css,
 *    public/js and public/images, used by App\Support\Asset::url().
 *
 * Runs with `php artisan optimize` (the launcher does that after an update).
 */
#[Signature('assets:cache')]
#[Description('Gabungkan CSS komponen dan simpan hash versi aset statis')]
class AssetsCache extends Command
{
    public function handle(): int
    {
        $bundle = self::bundle();
        $target = public_path('css/components.css');
        if (! is_file($target) || self::normalize((string) file_get_contents($target)) !== self::normalize($bundle)) {
            File::put($target, $bundle);
        }

        $versions = [];
        foreach (['css', 'js', 'images'] as $dir) {
            foreach (File::allFiles(public_path($dir)) as $file) {
                $path = $dir.'/'.str_replace('\\', '/', $file->getRelativePathname());
                $versions[$path] = Asset::hash($file->getPathname());
            }
        }
        ksort($versions);

        File::put(Asset::manifestPath(), '<?php return '.var_export($versions, true).';'.PHP_EOL);
        Asset::flush();
        $this->components->info('Aset statis: '.count($versions).' file diberi versi.');

        return self::SUCCESS;
    }

    /** Concatenation of the component stylesheets, in file-name order. */
    public static function bundle(): string
    {
        $parts = ["/* GENERATED by `php artisan assets:cache` from css/components/*.css - edit those files, not this one. */\n"];
        $files = File::files(public_path('css/components'));
        usort($files, fn ($a, $b): int => strcmp($a->getFilename(), $b->getFilename()));
        foreach ($files as $file) {
            $parts[] = "\n/* ".$file->getFilename()." */\n".self::normalize(rtrim((string) file_get_contents($file->getPathname())))."\n";
        }

        return implode('', $parts);
    }

    private static function normalize(string $css): string
    {
        return str_replace("\r\n", "\n", $css);
    }
}
